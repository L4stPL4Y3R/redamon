export const TRUFFLEHOG_DETECTOR_COUNT = TRUFFLEHOG_DETECTORS.length

/** Case-insensitive substring match, for the picker's filter box. */
export function filterDetectors(query: string): readonly string[] {
  const q = query.trim().toLowerCase()
  if (!q) return TRUFFLEHOG_DETECTORS
  return TRUFFLEHOG_DETECTORS.filter(d => d.toLowerCase().includes(q))
}

/**
 * Splits a comma-separated detector field into trimmed, non-empty tokens.
 * Shared by the picker and the validator so "what is selected" is decided once.
 */
export function parseDetectorList(raw: string): string[] {
  return String(raw ?? '').split(',').map(s => s.trim()).filter(Boolean)
}

/** Names in the field that TruffleHog will reject. Empty when all are valid. */
export function unknownDetectors(raw: string): string[] {
  const known = new Set(TRUFFLEHOG_DETECTORS)
  return parseDetectorList(raw).filter(d => !known.has(d))
}
